"""Generate the strategy reference from registered values and gate predicates."""
from __future__ import annotations

import argparse
import ast
from dataclasses import asdict
import hashlib
import inspect
import json
from pathlib import Path

from tennis_wc.props import calibration, registry, strategy
from tennis_wc.props import evidence_contract

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / 'docs/generated_strategy_reference.md'


def render_reference() -> str:
    lines = ['# Tennis strategy reference (generated)', '',
             'Regenerate with `PYTHONPATH=src python scripts/generate_strategy_reference.py`.',
             'Do not edit this file by hand. These are registered rules, not proof of profitable performance.', '',
             '## Family value profiles', '',
             '| Family | Minimum raw probability | Minimum edge | Minimum odds | Maximum odds |',
             '|---|---:|---:|---:|---:|']
    for family in sorted(strategy.SUPPORTED_FAMILIES):
        p=asdict(registry.value_profile_for_family(family))
        lines.append(f"| {family} | {p['min_probability']} | {p['min_edge']} | {p['min_odds']} | {p['max_odds']} |")
    lines += ['', '## Registered strategy constants', '', '| Name | Value |', '|---|---|']
    for key,value in sorted(vars(strategy).items()):
        if key.isupper() and not key.startswith('_') and isinstance(value,(str,int,float,bool,set)):
            if isinstance(value,set): value=sorted(value)
            lines.append(f'| `{key}` | `{json.dumps(value,ensure_ascii=False)}` |')
    lines += ['', '## Evidence and reliability', '',
              f'- Insufficient-evidence model weight: `{calibration.DEFAULT_MODEL_WEIGHT}`.',
              f'- Minimum sample for fitted weight: `{calibration.MIN_WEIGHT_SAMPLE}`.',
              f'- Evidence contract policy: `{evidence_contract.CONTRACT_POLICY}`.',
              '- Missing pricing receipts remain UNKNOWN. Rebuilding history does not manufacture pricing-time quality.',
              '- An as-of report requires the outcome to have been settled before its cutoff.',
              '- Estimated hit probability is not independently proven calibration.', '',
              '## Gate predicates from executable source', '',
              'The code below is extracted directly. Brier, credible-profit and probe paths must not be reduced to a Brier-only description.', '', '```python']
    source=inspect.getsource(strategy.recommendation_gate)
    names={'model_beats_market','profitable','credible_profit','early_evidence',
           'qualified','early_qualified','probe_qualified'}
    for node in ast.walk(ast.parse(source)):
        if isinstance(node,ast.Assign) and any(isinstance(t,ast.Name) and t.id in names for t in node.targets):
            lines += [ast.get_source_segment(source,node), '']
    lines += ['```', '',
              'Dependent drawdown, recency, stake and family restrictions are defined in `src/tennis_wc/props/strategy.py`.',
              'Per-leg eligibility is defined by `meets_formal_profile` and `leg_is_formal_candidate` in that file.', '',
              '## Source fingerprints', '', '| File | SHA256 |', '|---|---|']
    for module in (strategy,registry,calibration,evidence_contract):
        path=Path(inspect.getfile(module)).resolve()
        lines.append(f'| `{path.relative_to(ROOT)}` | `{hashlib.sha256(path.read_bytes()).hexdigest()}` |')
    return '\n'.join(lines)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output',type=Path,default=DEFAULT_OUTPUT)
    args=parser.parse_args()
    text=render_reference()
    if args.check:
        if not args.output.exists() or args.output.read_text()!=text:
            parser.exit(1,'Strategy reference is stale; regenerate it.\n')
        print('Strategy reference is current.')
    else:
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(text)
        print(args.output)


if __name__=='__main__':
    main()
