    parser.add_argument("--finish-map", type=Path)
    parser.add_argument("--betfair-dir", type=Path, required=True)
    parser.add_argument("--score-key", default="old_ability")
    parser.add_argument("--model-version", required=True)
    parser.add_argument(
        "--output-json",
        type=Path,
        default=Path("/private/tmp/au_betting_strategy_backtest.json"),
    )
    parser.add_argument(
        "--output-md",
        type=Path,
        default=Path("/private/tmp/au_betting_strategy_backtest.md"),
    )
