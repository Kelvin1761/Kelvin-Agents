def run_backtest(args: argparse.Namespace) -> dict:
    market_paths = sorted(args.betfair_dir.glob("dwbfpricesaus*.csv"))
    if not market_paths:
        raise SystemExit(f"No Betfair files found: {args.betfair_dir}")
    markets, market_audit = load_market_index(args.betfair_dir)
    if args.runtime_dataset:
        races, alignment = load_runtime_dataset_races(
            args.runtime_dataset,
            markets,
        )
        model_source = args.runtime_dataset
        model_source_label = "runtime_dataset"
    else:
        if not args.score_snapshot or not args.finish_map:
            raise SystemExit(
                "--score-snapshot and --finish-map are required unless "
                "--runtime-dataset is supplied."
            )
        races, alignment = load_snapshot_races(
            args.score_snapshot,
            args.finish_map,
            markets,
            score_key=args.score_key,
        )
        model_source = args.score_snapshot
        model_source_label = "score_snapshot"
    if not races:
        raise SystemExit("No aligned model races.")
    partitions = split_dates(races)
    candidates = strategy_grid()
    selected = {}
    discovery = {}
    for market in MARKETS:
        strategy, rows = discover_strategy(
            races,
            candidates,
            partitions["discovery"],
            market=market,
        )
        discovery[market] = public_discovery(rows)
        selected[market] = evaluate_selected(races, strategy, partitions)
    report = {
        "design": {
            "model_version": args.model_version,
            "score_key": args.score_key,
            "ranking_price_input": None,
            "decision_price": "morningwap",
            "settlement_prices": ["morningwap", "bsp"],
            "commission": COMMISSION,
            "selection_split": "60% discovery / 20% confirmation / 20% terminal by unique date",
            "promotion_gate": (
                "discovery halves non-negative; confirmation and terminal "
                "ROI positive with >=50 bets each; combined untouched-holdout "
                "bootstrap 95% ROI lower bound > 0"
            ),
            "candidate_count": len(candidates),
        },
        "sources": {
            model_source_label: source_fingerprint([model_source]),
            "betfair": source_fingerprint(market_paths),
        },
        "dataset": {
            "races": len(races),
            "horses": sum(len(race["selections"]) for race in races),
            "date_start": min(race["date"] for race in races),
            "date_end": max(race["date"] for race in races),
            "partition_dates": {
                name: sorted(dates)
                for name, dates in partitions.items()
            },
            "market_index": market_audit,
            "alignment": alignment,
        },
        "baselines": baseline_rows(races, partitions),
        "discovery_shortlist": discovery,
        "selected": selected,
    }
    if args.finish_map:
        report["sources"]["finish_map"] = source_fingerprint([args.finish_map])
    return report


