"""Production scoring adapter for the AU complete-day prediction producer.

The independently audited serving bundle must cover every possible source read,
including Facts, resource/cache files, and explicitly observed absent paths. This adapter verifies that declaration;
it cannot establish historical availability or completeness by itself. Each call
uses a fresh process so fitted coefficients and import-time caches cannot leak
between days or arms. Only the existing six outer coefficients are supported.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import subprocess
import sys

from au_prediction_intake import content_hash, _require, _time


def _file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _verify_assets(assets):
    _require(bool(assets), "serving_assets_missing")
    paths = [str(Path(row["path"]).resolve()) for row in assets]
    _require(len(paths) == len(set(paths)), "duplicate_serving_asset")
    for row in assets:
        state = row.get("state", "file")
        _require(state in {"file", "absent"}, "invalid_serving_asset_state")
        if state == "absent":
            _require(row.get("sha256") is None, "absent_serving_asset_has_hash")
            _require(not Path(row["path"]).exists(), "absent_serving_asset_appeared")
        else:
            _require(_file_hash(row["path"]) == row["sha256"], "serving_asset_changed")


def predict_production(race, state, profile):
    """Predict with score_logic_data and its final production safety/tie ranking.

    input.serving_bundle binds a separate audit artifact to all runtime sources;
    profile.serving_code binds algorithm files, while profile.environment locks
    the complete child environment. No audit PASS is generated by this module.
    Fitted state is {matrix_weights: <the exact six registered keys>}.
    """
    _require(set(race) == {"race_id", "date", "prediction_at", "input"},
             "adapter_received_labels_or_extra_race_fields")
    inp = race["input"]
    bundle = inp.get("serving_bundle", {})
    audit_ref = bundle.get("audit_artifact", {})
    _require(audit_ref.get("path") and audit_ref.get("sha256"), "serving_audit_missing")
    _require(_file_hash(audit_ref["path"]) == audit_ref["sha256"], "serving_audit_changed")
    audit = json.loads(Path(audit_ref["path"]).read_text())
    assets = bundle.get("assets", [])
    _require(audit.get("status") == "PASS" and audit.get("scope") == "complete_serving_reads",
             "serving_source_audit_not_passed")
    _require(audit.get("race_id") == race["race_id"] and audit.get("input_hash") ==
             content_hash({k: v for k, v in inp.items() if k != "serving_bundle"}),
             "serving_audit_input_binding_changed")
    _require(audit.get("assets_hash") == content_hash(assets), "serving_audit_assets_changed")
    _require(audit.get("prediction_at") == race["prediction_at"], "serving_audit_cutoff_changed")
    _require(all(row.get("audit") == "PASS" and
                 _time(row["observed_absent_at"] if row.get("state") == "absent"
                       else row["available_at"]) <= _time(race["prediction_at"])
                 for row in assets), "serving_future_or_flagged_source")
    path = str(Path(inp["logic_path"]).resolve())
    _require(path in {str(Path(a["path"]).resolve()) for a in assets}, "logic_asset_not_bound")
    code = profile.get("serving_code", [])
    _verify_assets(code)
    required_code = {Path(__file__).resolve(), Path(__file__).with_name("au_auto_orchestrator.py").resolve()}
    _require(required_code <= {Path(a["path"]).resolve() for a in code}, "serving_entry_code_not_bound")
    environment = profile.get("environment")
    _require(isinstance(environment, dict) and environment.get("PYTHONDONTWRITEBYTECODE") == "1"
             and environment.get("WC_DISABLE_POST_SUCCESS_DEPLOY") == "1"
             and all(isinstance(k, str) and isinstance(v, str) for k, v in environment.items()),
             "serving_environment_not_locked")
    _require(audit.get("environment_hash") == content_hash(environment), "serving_environment_audit_changed")
    _require(profile.get("fitted") == (state is not None), "serving_fit_state_mismatch")
    _verify_assets(assets)
    payload = {"logic_path": path, "runner_ids": inp["runner_ids"], "state": state,
               "going_override": inp.get("going_override")}
    completed = subprocess.run([sys.executable, "-B", str(Path(__file__).resolve()), "--worker"],
                               input=json.dumps(payload), text=True, capture_output=True,
                               env=dict(environment), check=True, timeout=60)
    # Reader mutation or source replacement is a hard failure, never fallback.
    _verify_assets(assets)
    _verify_assets(code)
    _require(_file_hash(audit_ref["path"]) == audit_ref["sha256"], "serving_audit_changed")
    result = json.loads(completed.stdout)
    result["serving_audit_hash"] = audit_ref["sha256"]
    result["serving_code_hash"] = content_hash(code)
    result["serving_environment_hash"] = content_hash(environment)
    return result


def _score_worker(payload):
    """Internal isolated scorer; provenance is enforced by the parent boundary."""
    import math
    from contextlib import redirect_stdout
    from au_racing_engine.scoring import MATRIX_WEIGHTS
    import au_auto_orchestrator as auto
    state = payload.get("state")
    if state is not None:
        _require(isinstance(state, dict) and set(state) == {"matrix_weights"}, "unsupported_serving_fit_state")
        weights = state["matrix_weights"]
        _require(isinstance(weights, dict) and set(weights) == set(MATRIX_WEIGHTS), "serving_dimension_keys_changed")
        _require(all(type(v) in (int, float) and math.isfinite(v) and v >= 0 for v in weights.values()),
                 "invalid_serving_coefficients")
        MATRIX_WEIGHTS.update(weights)
    # Production informational messages must not contaminate the JSON protocol.
    with redirect_stdout(sys.stderr):
        logic = auto.score_logic_data(Path(payload["logic_path"]), payload.get("going_override"))
    roster = payload["runner_ids"]
    horses = logic["horses"]
    _require(len(roster) == len(set(roster)) and set(horses) == set(roster), "serving_runner_roster_changed")
    ranking = [str(row["horse_number"]) for row in logic["python_auto_verdict"]["ranking"]]
    _require(len(ranking) == len(roster) and set(ranking) == set(roster), "serving_final_ranking_roster_changed")
    return {"ability": {n: horses[n]["python_auto"]["ability_score"] for n in roster}, "ranking": ranking}


if __name__ == "__main__":
    _require(sys.argv[1:] == ["--worker"], "worker_only_entry")
    print(json.dumps(_score_worker(json.load(sys.stdin)), allow_nan=False))
